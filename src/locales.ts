const LOCALE_TEXT: Record<BuiltInLocale, TranslatedLocaleText> = {
  "en-US": EN_US,
  "zh-TW": ZH_TW,
  "zh-CN": ZH_CN,
  "ja-JP": JA_JP,
  "ko-KR": KO_KR,
  "es-ES": ES_ES,
  "fr-FR": FR_FR,
  "de-DE": DE_DE,
  "pt-BR": PT_BR,
  "ru-RU": RU_RU,
};

function resolveBuiltInLocale(locale: string): BuiltInLocale {
  const normalized = locale.toLowerCase();
  if (
    normalized === "zh-tw" ||
    normalized === "zh-hk" ||
    normalized === "zh-mo" ||
    normalized.startsWith("zh-hant")
  )
    return "zh-TW";
  if (
    normalized === "zh" ||
    normalized === "zh-cn" ||
    normalized === "zh-sg" ||
    normalized.startsWith("zh-hans")
  )
    return "zh-CN";
  if (normalized.startsWith("ja")) return "ja-JP";
  if (normalized.startsWith("ko")) return "ko-KR";
  if (normalized.startsWith("es")) return "es-ES";
  if (normalized.startsWith("fr")) return "fr-FR";
  if (normalized.startsWith("de")) return "de-DE";
  if (normalized.startsWith("pt")) return "pt-BR";
  if (normalized.startsWith("ru")) return "ru-RU";
  return "en-US";
}

export function resolveFormattingLocale(locale: string): string {
  try {
    return Intl.getCanonicalLocales(locale)[0] ?? "en-US";
  } catch {
    return "en-US";
  }
}

export function getBuiltInLocaleText(locale: string): TranslatedLocaleText {
  return LOCALE_TEXT[resolveBuiltInLocale(locale)];
}
